-- Remove duplicate foreign key constraint that's causing the "more than one relationship" error
-- Check current foreign key constraints on property_applications table
SELECT 
    tc.constraint_name, 
    tc.table_name, 
    kcu.column_name, 
    ccu.table_name AS foreign_table_name,
    ccu.column_name AS foreign_column_name 
FROM 
    information_schema.table_constraints AS tc 
    JOIN information_schema.key_column_usage AS kcu
      ON tc.constraint_name = kcu.constraint_name
      AND tc.table_schema = kcu.table_schema
    JOIN information_schema.constraint_column_usage AS ccu
      ON ccu.constraint_name = tc.constraint_name
      AND ccu.table_schema = tc.table_schema
WHERE tc.constraint_type = 'FOREIGN KEY' 
  AND tc.table_name='property_applications'
  AND kcu.column_name = 'property_id';

-- Drop the duplicate foreign key constraint to fix the relationship ambiguity
-- This will keep the primary constraint and remove the duplicate one
ALTER TABLE public.property_applications 
DROP CONSTRAINT IF EXISTS fk_property_applications_property_id;

